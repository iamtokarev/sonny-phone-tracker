// Generates src/protocol.gen.ts from the state feed's Pydantic models (src/sonny/dashboard/protocol.py).
// The banner records the schema's sha256, which tests/test_dashboard_protocol.py checks, so a stale file
// fails pytest without Node. `--check` exits 1 instead of writing when the file would change.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const web = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(web, "src/protocol.gen.ts");

const text = execFileSync("uv", ["run", "python", "-m", "sonny.dashboard.protocol"], {
  cwd: resolve(web, ".."),
  encoding: "utf8",
});
const hash = createHash("sha256").update(text).digest("hex");
const banner = [
  "/* eslint-disable */",
  "// Generated by `npm run gen:protocol` from src/sonny/dashboard/protocol.py. Do not edit.",
  `// schema sha256: ${hash}`,
].join("\n");

const ts = await compile(JSON.parse(text), "DashboardProtocol", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: false, semi: true, printWidth: 120, trailingComma: "all" },
});

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== ts) {
    console.error("src/protocol.gen.ts is stale: run npm run gen:protocol");
    process.exit(1);
  }
} else {
  writeFileSync(out, ts);
}
